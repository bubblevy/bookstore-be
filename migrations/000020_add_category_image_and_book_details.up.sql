ADD COLUMN IF NOT EXISTS length NUMERIC(6, 2) NOT NULL DEFAULT 0,
ADD COLUMN IF NOT EXISTS width NUMERIC(6, 2) NOT NULL DEFAULT 0,
ADD COLUMN IF NOT EXISTS height NUMERIC(6, 2) NOT NULL DEFAULT 0,
ADD COLUMN IF NOT EXISTS condition VARCHAR(100) NOT NULL DEFAULT 'New';
